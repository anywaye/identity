package useraudit


import (
	"context"
	"fmt"

	"github.com/anywaye/identity/internal/platform/db"
)

const auditColumns = `id, user_id, action, actor_user_id, actor_key_id, trace_id, occurred_at`

// Store is the user_audit_log table.
type Store struct {
	pool db.Pool
}

// NewStore returns a Store backed by pool.
func NewStore(pool db.Pool) *Store { return &Store{pool: pool} }

// Pool returns the querier for statements that need no transaction.
//
// Append does not use it — Append is always handed the transaction's querier — and it
// exists because the pool is the thing the constructor was given, so a caller that
// wants to read the table directly (a test, an operator with psql) should not have to
// reach into the struct for it.
func (s *Store) Pool() db.Querier { return s.pool }

// Append writes one record and returns the stored row.
//
// q is a db.Querier rather than the pool because THIS IS CALLED FROM INSIDE THE
// TRANSACTION that the mutation ran in. That is the whole of the same-transaction
// guarantee: the audit row and the rows it describes are written by one transaction,
// so there is no interleaving in which a disable is visible without its record. A
// store that reached for its own pool here would be writing the audit row in a SECOND
// transaction, which is the bug the requirement exists to prevent — and it would be
// invisible, because both writes would succeed.
//
// RETURNING rather than a follow-up read: the id is generated by the database, and
// reading it back afterwards would be a second statement in a transaction whose whole
// point is that there is only one of each.
func (s *Store) Append(ctx context.Context, q db.Querier, e Entry) (Record, error) {
	if err := e.validate(); err != nil {
		return Record{}, err
	}
	if q == nil {
		return Record{}, fmt.Errorf("appending a user audit record: no querier was supplied")
	}

	const query = `
		INSERT INTO user_audit_log
			(user_id, action, actor_user_id, actor_key_id, trace_id, occurred_at)
		VALUES ($1, $2, $3, $4, $5, $6)
		RETURNING ` + auditColumns

	row := q.QueryRow(ctx, query,
		e.UserID, string(e.Action), e.Actor.UserID, e.Actor.KeyID,
		e.Actor.TraceID, e.OccurredAt,
	)

	rec, err := scanRecord(row)
	if err != nil {
		return Record{}, fmt.Errorf("inserting a user audit record: %w", err)
	}
	return rec, nil
}

func scanRecord(row interface{ Scan(...any) error }) (Record, error) {
	var (
		rec    Record
		action string
	)
	err := row.Scan(
		&rec.ID, &rec.UserID, &action,
		&rec.ActorUserID, &rec.ActorKeyID, &rec.TraceID, &rec.OccurredAt,
	)
	if err != nil {
		return Record{}, err
	}
	rec.Action = Action(action)
	return rec, nil
}
