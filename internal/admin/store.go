package admin


import (
	"context"
	"fmt"
	"time"

	"github.com/anywaye/identity/internal/platform/db"
	"github.com/anywaye/identity/internal/platform/id"
)

const auditColumns = `id, account_id, action, actor_user_id, actor_key_id, target, affected, trace_id, occurred_at`

// Store is the account_audit_log table.
type Store struct {
	pool db.Pool
}

// NewStore returns a Store backed by pool.
func NewStore(pool db.Pool) *Store { return &Store{pool: pool} }

// Pool returns the querier for statements that need no transaction — List, and
// nothing else.
func (s *Store) Pool() db.Querier { return s.pool }

// Append writes one record and returns the stored row.
//
// q is a db.Querier rather than the pool because THIS IS CALLED FROM INSIDE THE
// TRANSACTION that the mutation ran in. That is the whole of the same-transaction
// guarantee: the audit row and the row it describes are written by the same
// transaction, so there is no interleaving in which one is visible without the
// other. A store that reached for its own pool here would be writing the audit
// row in a SECOND transaction, which is the bug the packet's requirement exists
// to prevent — and it would be invisible, because both writes would succeed.
//
// RETURNING rather than a follow-up read: the id is generated by the database,
// and reading it back afterwards would be a second statement in a transaction
// whose whole point is that there is only one of each.
func (s *Store) Append(ctx context.Context, q db.Querier, e Entry) (Record, error) {
	if err := e.validate(); err != nil {
		return Record{}, err
	}
	if q == nil {
		return Record{}, fmt.Errorf("appending an audit record: no querier was supplied")
	}

	const query = `
		INSERT INTO account_audit_log
			(account_id, action, actor_user_id, actor_key_id, target, affected, trace_id, occurred_at)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
		RETURNING ` + auditColumns

	row := q.QueryRow(ctx, query,
		e.AccountID, string(e.Action), e.Actor.UserID, e.Actor.KeyID,
		e.Target, e.Affected, e.Actor.TraceID, e.OccurredAt,
	)

	rec, err := scanRecord(row)
	if err != nil {
		return Record{}, fmt.Errorf("inserting an audit record: %w", err)
	}
	return rec, nil
}

// List returns one bounded page of an account's trail, newest first.
//
// The page size is NOT re-clamped here. It was checked in Page.normalised before
// the store was called, and a store that silently clamped a too-large limit would
// be a second implementation of the ceiling that could disagree with the first —
// which is how a bound becomes a number in one place and a different number in
// another.
func (s *Store) List(ctx context.Context, q db.Querier, accountID id.UUID, page Page) ([]Record, error) {
	if accountID.IsZero() {
		return nil, ErrInvitationNotRevocable
	}
	limit, err := page.Normalised()
	if err != nil {
		return nil, err
	}

	const query = `
		SELECT ` + auditColumns + ` FROM account_audit_log
		WHERE account_id = $1
		  AND ($2::timestamptz IS NULL OR (occurred_at, id) < ($2, $3))
		ORDER BY occurred_at DESC, id DESC
		LIMIT $4`

	before, beforeID, err := page.Cursor()
	if err != nil {
		return nil, err
	}

	rows, err := q.Query(ctx, query, accountID, nullTime(before), nullUUID(beforeID), limit)
	if err != nil {
		return nil, fmt.Errorf("reading the audit trail: %w", err)
	}
	defer rows.Close()

	var out []Record
	for rows.Next() {
		rec, err := scanRecord(rows)
		if err != nil {
			return nil, fmt.Errorf("reading the audit trail: %w", err)
		}
		out = append(out, rec)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("reading the audit trail: %w", err)
	}

	if len(out) == limit {
		last := out[len(out)-1]
		out[len(out)-1].Next = encodeCursor(last.OccurredAt, last.ID)
	}
	return out, nil
}

func nullTime(t time.Time) any {
	if t.IsZero() {
		return nil
	}
	return t
}

func nullUUID(u id.UUID) any {
	if u.IsZero() {
		return nil
	}
	return u
}

func scanRecord(row interface{ Scan(...any) error }) (Record, error) {
	var (
		rec    Record
		action string
	)
	err := row.Scan(
		&rec.ID, &rec.AccountID, &action, &rec.ActorUserID, &rec.ActorKeyID,
		&rec.Target, &rec.Affected, &rec.TraceID, &rec.OccurredAt,
	)
	if err != nil {
		return Record{}, err
	}
	rec.Action = Action(action)
	return rec, nil
}
